package com.example.mapstruct_demo.dto;

public class NameOrAlias {
    public String dateOfBirth;
    public String fullName;
    public String nameType;
    public String sourceSegment;
    public String spouseNameXpn;
    public String yearOfBirth;

    public String getDateOfBirth() {
        return dateOfBirth;
    }

    public void setDateOfBirth(String dateOfBirth) {
        this.dateOfBirth = dateOfBirth;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getNameType() {
        return nameType;
    }

    public void setNameType(String nameType) {
        this.nameType = nameType;
    }

    public String getSourceSegment() {
        return sourceSegment;
    }

    public void setSourceSegment(String sourceSegment) {
        this.sourceSegment = sourceSegment;
    }

    public String getSpouseNameXpn() {
        return spouseNameXpn;
    }

    public void setSpouseNameXpn(String spouseNameXpn) {
        this.spouseNameXpn = spouseNameXpn;
    }

    public String getYearOfBirth() {
        return yearOfBirth;
    }

    public void setYearOfBirth(String yearOfBirth) {
        this.yearOfBirth = yearOfBirth;
    }
}
