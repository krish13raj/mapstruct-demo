package com.example.mapstruct_demo.dto;

public class AddressRecord {
    public String addressText;
    public String dateReported;
    public String dwellingType;
    public String lastSubcriberCodeReporting;
    public String lastUpdateDate;
    public String numberTimesReported;
    public String originationCode;
    public String position;
    public String sourceSegment;
    public String y2KDateFirstReported;
    public String y2KLastUpdatedDate;

    public String getAddressText() {
        return addressText;
    }

    public void setAddressText(String addressText) {
        this.addressText = addressText;
    }

    public String getDateReported() {
        return dateReported;
    }

    public void setDateReported(String dateReported) {
        this.dateReported = dateReported;
    }

    public String getDwellingType() {
        return dwellingType;
    }

    public void setDwellingType(String dwellingType) {
        this.dwellingType = dwellingType;
    }

    public String getLastSubcriberCodeReporting() {
        return lastSubcriberCodeReporting;
    }

    public void setLastSubcriberCodeReporting(String lastSubcriberCodeReporting) {
        this.lastSubcriberCodeReporting = lastSubcriberCodeReporting;
    }

    public String getLastUpdateDate() {
        return lastUpdateDate;
    }

    public void setLastUpdateDate(String lastUpdateDate) {
        this.lastUpdateDate = lastUpdateDate;
    }

    public String getNumberTimesReported() {
        return numberTimesReported;
    }

    public void setNumberTimesReported(String numberTimesReported) {
        this.numberTimesReported = numberTimesReported;
    }

    public String getOriginationCode() {
        return originationCode;
    }

    public void setOriginationCode(String originationCode) {
        this.originationCode = originationCode;
    }

    public String getPosition() {
        return position;
    }

    public void setPosition(String position) {
        this.position = position;
    }

    public String getSourceSegment() {
        return sourceSegment;
    }

    public void setSourceSegment(String sourceSegment) {
        this.sourceSegment = sourceSegment;
    }

    public String getY2KDateFirstReported() {
        return y2KDateFirstReported;
    }

    public void setY2KDateFirstReported(String y2KDateFirstReported) {
        this.y2KDateFirstReported = y2KDateFirstReported;
    }

    public String getY2KLastUpdatedDate() {
        return y2KLastUpdatedDate;
    }

    public void setY2KLastUpdatedDate(String y2KLastUpdatedDate) {
        this.y2KLastUpdatedDate = y2KLastUpdatedDate;
    }
}
