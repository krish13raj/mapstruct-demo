package com.example.mapstruct_demo.dto;

public class InquiryRecord {
    public String appIndex;
    public String industryCode;
    public String inquiryDate;
    public String loanAmount;
    public String sourceSegment;
    public String subscriberName;
    public String subscriberNumber;
    public String termsDuration;
    public String y2kInquiryDate;

    public String getAppIndex() {
        return appIndex;
    }

    public void setAppIndex(String appIndex) {
        this.appIndex = appIndex;
    }

    public String getIndustryCode() {
        return industryCode;
    }

    public void setIndustryCode(String industryCode) {
        this.industryCode = industryCode;
    }

    public String getInquiryDate() {
        return inquiryDate;
    }

    public void setInquiryDate(String inquiryDate) {
        this.inquiryDate = inquiryDate;
    }

    public String getLoanAmount() {
        return loanAmount;
    }

    public void setLoanAmount(String loanAmount) {
        this.loanAmount = loanAmount;
    }

    public String getSourceSegment() {
        return sourceSegment;
    }

    public void setSourceSegment(String sourceSegment) {
        this.sourceSegment = sourceSegment;
    }

    public String getSubscriberName() {
        return subscriberName;
    }

    public void setSubscriberName(String subscriberName) {
        this.subscriberName = subscriberName;
    }

    public String getSubscriberNumber() {
        return subscriberNumber;
    }

    public void setSubscriberNumber(String subscriberNumber) {
        this.subscriberNumber = subscriberNumber;
    }

    public String getTermsDuration() {
        return termsDuration;
    }

    public void setTermsDuration(String termsDuration) {
        this.termsDuration = termsDuration;
    }

    public String getY2kInquiryDate() {
        return y2kInquiryDate;
    }

    public void setY2kInquiryDate(String y2kInquiryDate) {
        this.y2kInquiryDate = y2kInquiryDate;
    }
}
