package com.example.mapstruct_demo.dto;

public class ScoringRecord {
    public String firstReasonCode;
    public String secondReasonCode;
    public String thirdReasonCode;
    public String fourthReasonCode;
    public String fifthReasonCode;
    public String modelTypeIndicator;
    public String scoreSign;
    public String score;

    public String getFirstReasonCode() {
        return firstReasonCode;
    }

    public void setFirstReasonCode(String firstReasonCode) {
        this.firstReasonCode = firstReasonCode;
    }

    public String getSecondReasonCode() {
        return secondReasonCode;
    }

    public void setSecondReasonCode(String secondReasonCode) {
        this.secondReasonCode = secondReasonCode;
    }

    public String getThirdReasonCode() {
        return thirdReasonCode;
    }

    public void setThirdReasonCode(String thirdReasonCode) {
        this.thirdReasonCode = thirdReasonCode;
    }

    public String getFourthReasonCode() {
        return fourthReasonCode;
    }

    public void setFourthReasonCode(String fourthReasonCode) {
        this.fourthReasonCode = fourthReasonCode;
    }

    public String getFifthReasonCode() {
        return fifthReasonCode;
    }

    public void setFifthReasonCode(String fifthReasonCode) {
        this.fifthReasonCode = fifthReasonCode;
    }

    public String getModelTypeIndicator() {
        return modelTypeIndicator;
    }

    public void setModelTypeIndicator(String modelTypeIndicator) {
        this.modelTypeIndicator = modelTypeIndicator;
    }

    public String getScoreSign() {
        return scoreSign;
    }

    public void setScoreSign(String scoreSign) {
        this.scoreSign = scoreSign;
    }

    public String getScore() {
        return score;
    }

    public void setScore(String score) {
        this.score = score;
    }
}
